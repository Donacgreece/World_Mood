alter table public.mood_entries add column if not exists event_slug text;

create table if not exists public.mood_reports (
  id bigint generated by default as identity primary key,
  entry_id uuid not null references public.mood_entries(id) on delete cascade,
  actor_hash text not null,
  reason text not null default 'community',
  created_at timestamptz not null default now(),
  unique(entry_id, actor_hash)
);

create table if not exists public.world_questions (
  id uuid primary key default gen_random_uuid(),
  question text not null,
  options jsonb not null,
  active_from timestamptz not null default now(),
  active_until timestamptz not null default (now() + interval '30 days'),
  created_at timestamptz not null default now(),
  check (jsonb_typeof(options) = 'array')
);

create table if not exists public.world_question_votes (
  question_id uuid not null references public.world_questions(id) on delete cascade,
  actor_hash text not null,
  choice smallint not null,
  updated_at timestamptz not null default now(),
  primary key(question_id, actor_hash)
);

create table if not exists public.mood_events (
  slug text primary key,
  title text not null,
  emoji text not null default '✨',
  active_from timestamptz not null,
  active_until timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.mood_circles (
  id uuid primary key default gen_random_uuid(),
  code varchar(8) not null unique,
  creator_hash text not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days')
);

create table if not exists public.mood_circle_entries (
  id bigint generated by default as identity primary key,
  circle_id uuid not null references public.mood_circles(id) on delete cascade,
  actor_hash text not null,
  mood_score numeric(3,1) not null check (mood_score between 1 and 10),
  emotion text not null check (emotion in ('great','good','calm','okay','low','stressed','angry','tired')),
  created_at timestamptz not null default now()
);

create index if not exists mood_reports_entry_idx on public.mood_reports(entry_id);
create index if not exists world_question_votes_question_idx on public.world_question_votes(question_id);
create index if not exists mood_circle_entries_circle_idx on public.mood_circle_entries(circle_id, created_at desc);
create index if not exists mood_circle_entries_actor_idx on public.mood_circle_entries(actor_hash, created_at desc);
create index if not exists mood_entries_context_idx on public.mood_entries(context_tag, created_at desc) where context_tag is not null;
create index if not exists mood_entries_event_idx on public.mood_entries(event_slug, created_at desc) where event_slug is not null;

